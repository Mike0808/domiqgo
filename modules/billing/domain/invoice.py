"""Правила счёта — чистые, без Django и без хранения (шаг H3).

Инварианты спецификации Billing, переехавшие из легаси-сервисов:

- **инв. 2** — выставленный счёт неизменяем: ни пересчитать, ни выставить
  второй раз;
- **инв. 5** — счёт без договора не предъявляется: выставлять некому;
- **ADR-0013** — срок оплаты фиксируется в счёте значением на момент
  выставления: смена политики не делает старые счета просроченными;
- **ADR-0015** — «оплачен» — вывод сверки: признано больше нуля и не меньше
  итога. Частичная оплата счёт не закрывает.
"""

from datetime import timedelta

UNPAID = "unpaid"
PENDING = "pending"
PAID = "paid"
STATUS_LABELS = {UNPAID: "Не оплачено", PENDING: "На проверке",
                 PAID: "Оплачено"}


class InvoiceAlreadyIssued(Exception):
    """Выставленный счёт неизменяем (инв. 2 Billing): ни пересчитать, ни
    выставить второй раз."""


class DraftWithoutTenancy(Exception):
    """Счёт без договора не предъявляется (инв. 5): сначала назначьте
    договор в форме начисления."""


class MissingTenancyError(Exception):
    """На дату начала периода у объекта нет договора — счёт выставлять некому.

    Отказ, а не счёт без аренды: молчаливый ноль в строке «Аренда» ничем не
    лучше молчаливого нуля за подогрев (дефект №29), а адресата у такого
    счёта всё равно нет — Billing перекладывает счёт на договор (E2).
    """


def due_date_for(moment, due_days: int):
    """Срок оплаты — от момента предъявления, значением (ADR-0013)."""
    return moment.date() + timedelta(days=due_days)


def settled_status(settled_total, total, has_pending_claim: bool) -> str:
    """Статус счёта — вывод, а не поле (E3, дефект №15): признано ли не
    меньше итога; «на проверке», пока есть заявленный платёж."""
    if settled_total > 0 and settled_total >= total:
        return PAID
    if has_pending_claim:
        return PENDING
    return UNPAID
