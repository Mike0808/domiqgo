"""Объект недвижимости — корень агрегата Properties.

Состав подведённых услуг и норматив подогрева — атрибуты объекта, а не
отдельные сущности: они не имеют смысла в отрыве от него и не меняются
независимо.

**Класс называется `Apartment`, а не `Property`.** Спецификация говорит
«объект», и обобщение напрашивается — но на P1 объект и есть квартира, а
целевой пользователь это собственник двух-трёх квартир. Дома, коммерческие
помещения и всё, ради чего нужно общее слово, отнесены в P3. Переименовать
дешевле тогда, когда появится второй вид объекта, чем содержать абстракцию,
которой сегодня нечего обобщать.

Здесь только stdlib. Ни Django, ни базы.
"""

from dataclasses import dataclass, replace
from datetime import date
from decimal import Decimal


class LabelMissing(ValueError):
    """У объекта нет наименования.

    Инвариант 3 спецификации: наименование — единственное, по чему владелец
    отличает одну квартиру от другой в интерфейсе. Объект без него превращает
    список в набор безымянных строк, а выпадающий список выбора — в загадку.
    Адрес этой роли не играет: он нужен отчёту, а не глазу, и у двух квартир в
    одном доме совпадает.
    """


def ensure_label_is_set(label: str) -> None:
    if not (label or "").strip():
        raise LabelMissing(
            "У объекта должно быть наименование — то, как вы называете его "
            "между собой: «Ленина», «студия у метро».")


class HeatNormMissing(ValueError):
    """К объекту подведена горячая вода, а норматив подогрева не задан.

    Гкал = объём × норматив, поэтому нулевой норматив даёт нулевую сумму за
    подогрев: строка в счёте есть, сумма нулевая, ошибки нет — владелец
    недополучает деньги молча и замечает это только сверкой с квитанцией УК
    (дефект №29 гап-анализа). Величина не выводится ни из чего: она подомовая
    и берётся из квитанции управляющей компании. Единственный правильный ответ
    — отказаться.
    """


def ensure_heat_norm_is_set(has_hot_water: bool, gvs_heat_norm) -> None:
    """Инвариант 1 спецификации.

    Отдельной функцией, а не проверкой в конструкторе агрегата: объект с
    незаполненным нормативом мог быть заведён до исправления дефекта №29 —
    `Model.clean` не срабатывает на `objects.create`. Отказ в конструкторе
    сделал бы такой объект нечитаемым целиком, тогда как достаточно отказать
    в начислении. Тот же выбор, что у Metering с дубликатами показаний.
    """
    # `Decimal("0")` ложно, `None` (поле оставили пустым) — тоже.
    if has_hot_water and (gvs_heat_norm or 0) <= 0:
        raise HeatNormMissing(
            "При подведённой горячей воде норматив подогрева обязателен и "
            "больше нуля. Возьмите его из квитанции управляющей компании "
            "(обычно 0,05–0,065 Гкал/м³). Пока он не задан, подогрев в счёт "
            "не попадает, и вы недополучаете эти деньги.")


@dataclass(frozen=True)
class Apartment:
    """Объект недвижимости: как называется, что подведено, в эксплуатации ли.

    Замкнутый: изменение состояния порождает новый объект, а не правит
    существующий. Так вызывающий не может изменить агрегат мимо команды.
    """

    apartment_id: int
    label: str
    has_cold_water: bool
    has_hot_water: bool
    has_sewage: bool
    gvs_heat_norm: Decimal
    #: Почтовый адрес одной строкой — то, что печатается в отчёте бухгалтеру.
    #: Не обязателен: у владельца двух квартир он в голове, и требовать его
    #: при заведении объекта значит мешать ради формальности.
    address: str = ""
    decommissioned_on: date | None = None

    @property
    def in_service(self) -> bool:
        """Действует объект или выведен из эксплуатации."""
        return self.decommissioned_on is None

    def decommission(self, on_date: date) -> "Apartment":
        """Вывести из эксплуатации: продан, больше не сдаётся.

        Действующий договор при этом **не прекращается**
        ([ADR-0009](../../../docs/architecture/adr/0009-property-decommission-and-active-tenancy.md)):
        договор — юридический факт, и система не вправе отменять его из-за
        административной отметки. Проверить, живёт ли кто-то в объекте,
        Properties не может — обращение к Tenancy замкнуло бы цикл. Значит
        выбор был не между «инвариант тут или там», а между «инвариант в
        прикладном слое» и «инварианта нет».

        Повторный вывод переставляет дату: команда описывает желаемое
        состояние, а не переход.
        """
        return replace(self, decommissioned_on=on_date)

    def ensure_billable(self) -> None:
        """Отказать, если по объекту нельзя начислять.

        Сегодня условие одно — норматив подогрева при подведённой ГВС.
        Спрашивает Billing перед расчётом: правило принадлежит объекту, а
        решение «поэтому счёт не считается» — счёту.
        """
        ensure_heat_norm_is_set(self.has_hot_water, self.gvs_heat_norm)

    def rename(self, label: str, address: str) -> "Apartment":
        """Изменить наименование или адрес.

        Наименование проверяется, адрес — нет: первое видит владелец в списке,
        второе печатается в отчёте, и пустой адрес там не ошибка, а «не
        заполнено».
        """
        ensure_label_is_set(label)
        return replace(self, label=label.strip(), address=address.strip())

    def change_service_composition(self, has_cold_water: bool,
                                   has_hot_water: bool, has_sewage: bool,
                                   gvs_heat_norm) -> "Apartment":
        """Изменить состав подведённых услуг и норматив подогрева.

        Провели горячую воду — обязан появиться и норматив: иначе объект
        начнёт молча недоначислять за подогрев, чем и был дефект №29.
        """
        ensure_heat_norm_is_set(has_hot_water, gvs_heat_norm)
        return replace(self, has_cold_water=has_cold_water,
                       has_hot_water=has_hot_water, has_sewage=has_sewage,
                       gvs_heat_norm=gvs_heat_norm)

    def recommission(self) -> "Apartment":
        """Вернуть в эксплуатацию.

        Без этой команды первая же ошибка вывода превращалась бы в тупик.
        """
        return replace(self, decommissioned_on=None)
