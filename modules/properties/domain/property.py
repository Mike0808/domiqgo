"""Объект недвижимости — корень агрегата Properties.

Состав подведённых услуг и норматив подогрева — атрибуты объекта, а не
отдельные сущности: они не имеют смысла в отрыве от него и не меняются
независимо.

**Класс называется `Apartment`, а не `Property`.** Спецификация говорит
«объект», и обобщение напрашивается — но на P1 объект и есть квартира, а
целевой пользователь это собственник двух-трёх квартир. Дома, коммерческие
помещения и всё, ради чего нужно общее слово, отнесены в P3. Переименовать
дешевле тогда, когда появится второй вид объекта, чем содержать абстракцию,
которой сегодня нечего обобщать.

Здесь только stdlib. Ни Django, ни базы.
"""

from dataclasses import dataclass, replace
from datetime import date
from decimal import Decimal


@dataclass(frozen=True)
class Apartment:
    """Объект недвижимости: как называется, что подведено, в эксплуатации ли.

    Замкнутый: изменение состояния порождает новый объект, а не правит
    существующий. Так вызывающий не может изменить агрегат мимо команды.
    """

    apartment_id: int
    label: str
    has_cold_water: bool
    has_hot_water: bool
    has_sewage: bool
    gvs_heat_norm: Decimal
    decommissioned_on: date | None = None

    @property
    def in_service(self) -> bool:
        """Действует объект или выведен из эксплуатации."""
        return self.decommissioned_on is None

    def decommission(self, on_date: date) -> "Apartment":
        """Вывести из эксплуатации: продан, больше не сдаётся.

        Действующий договор при этом **не прекращается**
        ([ADR-0009](../../../docs/architecture/adr/0009-property-decommission-and-active-tenancy.md)):
        договор — юридический факт, и система не вправе отменять его из-за
        административной отметки. Проверить, живёт ли кто-то в объекте,
        Properties не может — обращение к Tenancy замкнуло бы цикл. Значит
        выбор был не между «инвариант тут или там», а между «инвариант в
        прикладном слое» и «инварианта нет».

        Повторный вывод переставляет дату: команда описывает желаемое
        состояние, а не переход.
        """
        return replace(self, decommissioned_on=on_date)

    def recommission(self) -> "Apartment":
        """Вернуть в эксплуатацию.

        Без этой команды первая же ошибка вывода превращалась бы в тупик.
        """
        return replace(self, decommissioned_on=None)
