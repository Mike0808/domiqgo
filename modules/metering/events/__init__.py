"""Контракты доменных событий модуля: имена и полезная нагрузка.

Импортируются другими модулями наравне с `api/`. Публикуются только из
`application/` (правило 4.4) — единственного слоя, который знает, что операция
завершилась.

**Событие на сдачу комплекта, а не на каждое показание.** В каталоге целевой
карты (`02-target-map.md` §5) значилось `MeterReadingRecorded` с нагрузкой на
одно показание. Заменено сознательно: показания сдаются комплектом, и при
поштучной публикации Billing пересчитал бы счёт три-четыре раза подряд, причём
все промежуточные пересчёты — по заведомо неполным данным. Событие на
транзакцию, а не на строку.

**Подписчиков на шаге C2f нет ни у одного из трёх.** Пересчёт счёта после
сдачи показаний сегодня делает вызывающий, синхронно; перевод его на подписку
— часть шага **E4**, где счёт вообще перестаёт возникать сам собой (нарушение
№35 гап-анализа). Публиковать раньше, чем появится подписчик, — то же, что
сделали Tariffs на C1a: контракт объявлен, и подключение к нему не потребует
трогать Metering.
"""

from dataclasses import dataclass
from datetime import date
from decimal import Decimal


@dataclass(frozen=True)
class MeterReadingsSubmitted:
    """Комплект показаний за период сдан.

    `resources` — кортеж, а не список: событие неизменяемо целиком, включая
    свои поля. Автор пока выражен флагом «внесено жильцом»: ссылка на учётную
    запись появится вместе с Identity, до тех пор различать «жилец» и
    «владелец» достаточно.
    """

    apartment_id: int
    period: date
    resources: tuple[str, ...]
    entered_by_tenant: bool


@dataclass(frozen=True)
class MeterReadingCorrected:
    """Ранее внесённое показание исправлено.

    Отдельно от сдачи намеренно: сдача — нормальный ежемесячный ход событий,
    исправление — признание ошибки в уже сданных данных. На выставленный счёт
    они влияют по-разному, и подписчик обязан их различать. То же разделение
    принято в Tariffs между публикацией и исправлением версии.

    Прежнее значение едет в нагрузке, потому что подписчик должен понять
    масштаб расхождения, не обращаясь обратно в Metering.
    """

    apartment_id: int
    period: date
    resource: str
    previous_value: Decimal
    new_value: Decimal


@dataclass(frozen=True)
class MeterRegistered:
    """Прибор введён в учёт."""

    apartment_id: int
    resource: str
    serial_number: str
    initial_value: Decimal
    initial_date: date | None
