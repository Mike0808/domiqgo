"""Контракты доменных событий модуля: имена и полезная нагрузка.

Импортируются другими модулями наравне с `api/`. Публикуются только из
`application/` (правило 4.4).
"""

from dataclasses import dataclass
from datetime import datetime


@dataclass(frozen=True)
class PrivacyConsentGranted:
    """Согласие на обработку персональных данных зафиксировано.

    Подписчиков нет и не предполагается: событие ведётся ради аудита 152-ФЗ.
    Журнал шины хранит его наравне с прочими, и это ровно то, что нужно —
    независимый след того, что согласие было дано, вне таблицы, которую можно
    поправить.
    """

    account_id: int
    policy_version: str
    given_at: datetime
