"""Запись факта публикации в журнал."""

from dataclasses import asdict, is_dataclass
from typing import Any


def record(event: Any):
    """Записать событие в журнал — в транзакции того, кто публикует.

    Вызывается из `publish` до планирования доставки: если нагрузку не удаётся
    разложить, лучше упасть здесь, чем оставить запланированную доставку без
    журнальной записи.

    Модель импортируется внутри функции, а не сверху: `bus/__init__.py` тянет
    `publish`, то есть выполняется при загрузке приложения `bus` — раньше, чем
    реестр приложений готов принять объявление модели. Импорт наверху даёт
    `AppRegistryNotReady` при любой команде `manage.py`.
    """
    from .models import PublishedEvent

    return PublishedEvent.objects.create(
        event_type=f"{type(event).__module__}.{type(event).__qualname__}",
        payload=_payload_of(event),
    )


def _payload_of(event: Any) -> dict:
    """Разложить событие в словарь.

    Событие обязано быть **датаклассом** — единственное требование шины к его
    форме (базового класса у событий нет,
    [ADR-0027](../docs/architecture/adr/0027-event-bus-lives-outside-modules.md)).
    Требование не техническое: `asdict` работал бы и с `vars()`, но датакласс
    — это ещё и объявленные поля с аннотациями, а на них опираются
    архитектурные проверки правил 4.1 и 4.2.

    Ошибка поднимается сразу и роняет операцию издателя. Так и задумано:
    нагрузка, которую нельзя уложить в JSON, нарушает правило 4.2, а оно
    проверяется в CI — до продакшена такое событие не доедет.
    """
    if not is_dataclass(event) or isinstance(event, type):
        raise TypeError(
            f"{type(event).__name__} — не датакласс. Событие объявляется "
            "`@dataclass(frozen=True)` в modules/<модуль>/events/: шине нужны "
            "поля, чтобы записать нагрузку, а проверкам правил 4.1 и 4.2 — "
            "аннотации, чтобы их прочитать."
        )
    return asdict(event)
