"""Публикация события и доставка после коммита."""

import logging
from typing import Any

from django.db import transaction

from .journal import record
from .registry import subscribers_for

logger = logging.getLogger("bus")


def publish(event: Any) -> None:
    """Опубликовать событие: доставка — после коммита текущей транзакции.

    Внутри `atomic()` доставка отложена до фиксации: подписчик не должен
    увидеть факт, который затем откатится. Вне `atomic()` Django выполняет
    обратный вызов немедленно — и это верно, потому что публиковать без
    транзакции означает, что фиксировать нечего.

    Факт публикации попадает в журнал (`bus_published_event`) **до** того, как
    доставка запланирована, и в той же транзакции: откат уносит запись вместе
    с фактом, которого не было. Журнал нужен не доставке, а пересборке проекции
    признанных оплат — [ADR-0015](../docs/architecture/adr/0015-settlement-projection-in-billing.md).

    Функция ничего не возвращает и не сообщает, дошло ли событие: издателя это
    не касается. Судьба подписчика — в логе `bus`.
    """
    record(event)
    transaction.on_commit(lambda: _deliver(event))


def _deliver(event: Any) -> None:
    """Вызвать обработчики по одному, изолируя падение каждого.

    Без этого `try` шина не изолирует ничего: обратные вызовы `on_commit`
    выполняются после фиксации, поэтому откатить транзакцию издателя падение
    подписчика не может, **но прерывает остальные обратные вызовы и уходит в
    вызывающий код** — то есть в ответ HTTP. Один сломанный подписчик уронил бы
    и запрос, и доставку соседям.

    Ошибка не проглатывается, а пишется в лог с полным стеком: §2.6 оценки уже
    назвала слабость синхронной доставки — потерянный факт выглядит как тишина.
    Лог не устраняет её, но делает различимой.
    """
    for handler in subscribers_for(event):
        try:
            handler(event)
        except Exception:
            logger.exception(
                "Подписчик %s.%s упал на событии %s; остальные получат его "
                "как обычно",
                getattr(handler, "__module__", "?"),
                getattr(handler, "__qualname__", repr(handler)),
                type(event).__name__,
            )
